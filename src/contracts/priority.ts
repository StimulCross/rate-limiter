/**
 * Task selection priorities. Higher values represent higher priority.
 */
export enum Priority {
	/**
	 * Lowest selection priority.
	 */
	Lowest = 1,

	/**
	 * Low selection priority.
	 */
	Low = 2,

	/**
	 * Normal selection priority.
	 */
	Normal = 3,

	/**
	 * High selection priority.
	 */
	High = 4,

	/**
	 * Highest selection priority.
	 */
	Highest = 5,
}
